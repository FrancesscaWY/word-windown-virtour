import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { artwork, junctions, roads, stopAnchors } from './artwork-road-controls.mjs';
import { projectMapPosition } from '../src/components/map-projection.js';
import { parkCatalog } from '../src/data/park-catalog.js';

const root = new URL('../', import.meta.url);
const hash = data => createHash('sha256').update(data).digest('hex');
const artworkSha256 = hash(await readFile(new URL('public/assets/map.jpg', root)));
const nodes = [], shared = new Map();
const addNode = ([x, y]) => { const id = nodes.length + 1; nodes.push({ id, x: x / artwork.width * 100, y: y / artwork.height * 100 }); return id; };
for (const [name, point] of Object.entries(junctions)) if (roads.some(road => road.from === name || road.to === name)) shared.set(name, addNode(point));
const pixelDistance = (a, b) => Math.hypot(a[0] - b[0], a[1] - b[1]);
function smooth(points) {
  const output = [points[0]];
  for (let i = 0; i < points.length - 1; i++) {
    const a = points[Math.max(0, i - 1)], b = points[i], c = points[i + 1], d = points[Math.min(points.length - 1, i + 2)];
    const count = Math.max(1, Math.ceil(pixelDistance(b, c) / 2));
    for (let j = 1; j <= count; j++) {
      const t = j / count, t2 = t * t, t3 = t2 * t;
      output.push([0, 1].map(k => .5 * ((2 * b[k]) + (-a[k] + c[k]) * t + (2 * a[k] - 5 * b[k] + 4 * c[k] - d[k]) * t2 + (-a[k] + 3 * b[k] - 3 * c[k] + d[k]) * t3)));
    }
  }
  return output;
}
const traced = roads.map(road => {
  if (!shared.has(road.from) || !shared.has(road.to)) throw new Error(`Unknown junction in ${road.id}`);
  const pixels = smooth([junctions[road.from], ...road.via, junctions[road.to]]);
  const ids = [shared.get(road.from), ...pixels.slice(1, -1).map(addNode), shared.get(road.to)];
  return { id: road.id, kind: road.kind, nodeIds: ids };
});
const anchors = {};
for (const poi of parkCatalog.filter(p => p.position && p.locationVerified)) {
  const projected = projectMapPosition(poi.position);
  const target = stopAnchors[poi.id] ?? [projected.x / 100 * artwork.width, projected.y / 100 * artwork.height];
  const closest = nodes.reduce((best, node) => {
    const distance = pixelDistance(target, [node.x / 100 * artwork.width, node.y / 100 * artwork.height]);
    return !best || distance < best.distance ? { nodeId: node.id, distance } : best;
  }, null);
  anchors[poi.id] = closest.nodeId;
}
const data = { version: 1, kind: 'artwork-traced', artwork, artworkSha256, nodes, roads: traced, anchors };
const network = { ...data, sourceSha256: hash(JSON.stringify(data)) };
await writeFile(new URL('src/data/artwork-roads.js', root), `// Generated by node scripts/trace-artwork-roads.mjs. Hand-traced illustration, not geographic roads.\nexport const artworkRoads = ${JSON.stringify(network)};\n`);
console.log(`Traced ${traced.length} illustration paths, ${shared.size} junctions and ${nodes.length} sampled vertices.`);
