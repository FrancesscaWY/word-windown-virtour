import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { parkCatalog } from '../src/data/park-catalog.js';
import { externalAssets } from '../src/data/external-assets.js';
import { projectMapLine } from '../src/components/map-projection.js';
import { triangulate } from './map-triangulation.mjs';
import { artwork, controlPoints } from './map-control-points.mjs';
import { buildWalkingGraph } from '../server/ai/walking-network.ts';

const root = new URL('../', import.meta.url);
const read = path => readFile(new URL(path, root));
const raw = await read('public/assets/world-window-osm-source.json');
const data = JSON.parse(raw);
const nodes = new Map(data.elements.filter(e => e.type === 'node').map(e => [e.id, e]));
const [west, south, east, north] = externalAssets.map.bbox;
const percent = p => ({ x: (p.lon - west) / (east - west) * 100, y: (north - p.lat) / (north - south) * 100 });
const controls = controlPoints.map(c => {
  const source = c.node ? percent(nodes.get(c.node)) : parkCatalog.find(p => p.id === c.poi)?.position;
  if (!source) throw new Error(`Missing control source: ${c.label}`);
  return { ...c, source: [source.x, source.y], target: [c.pixel[0] / artwork.width * 100, c.pixel[1] / artwork.height * 100] };
});
for (const corner of [[0, 0], [100, 0], [100, 100], [0, 100]]) controls.push({ label: '画布边界', source: corner, target: corner });
const source = controls.map(c => c.source), target = controls.map(c => c.target);
const triangles = triangulate(source);
const area = (a, b, c) => (b[0] - a[0]) * (c[1] - a[1]) - (c[0] - a[0]) * (b[1] - a[1]);
const folds = triangles.filter(triangle => area(...triangle.map(i => source[i])) * area(...triangle.map(i => target[i])) <= 0);
if (folds.length) throw new Error(`Registration foldovers:\n${folds.map(t => t.map(i => controls[i].label).join(', ')).join('\n')}`);
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const calibration = { version: 1, artwork, artworkSha256: hash(await read('public/assets/map.jpg')), sourceSha256: hash(raw), source, target, triangles };
// The visible network and backend router share boundary/access rules, including
// recorded gate nodes lying exactly on the park boundary.
const graph = buildWalkingGraph(data, externalAssets.map.bbox);
const edges = new Set([...graph.edges].flatMap(([from, list]) => list.flatMap(edge => [`${edge.wayId}:${from}:${edge.to}`, `${edge.wayId}:${edge.to}:${from}`])));
const paths = [];
for (const way of data.elements) {
  const tags = way.tags ?? {};
  if (way.type !== 'way' || !tags.highway) continue;
  let d = '', previous = null;
  for (let i = 1; i < way.nodes.length; i++) {
    const a = nodes.get(way.nodes[i - 1]), b = nodes.get(way.nodes[i]);
    if (!a || !b || !edges.has(`${way.id}:${a.id}:${b.id}`)) { previous = null; continue; }
    const from = percent(a), to = percent(b);
    // Sample long original edges so a line follows the piecewise mesh, including
    // triangle crossings. Identical OSM junctions always share one projection.
    const { points } = projectMapLine([from, to], calibration);
    for (let step = previous === a.id ? 1 : 0; step < points.length; step++) {
      const p = points[step];
      d += `${step === 0 ? 'M' : 'L'}${(p.x*artwork.width/100).toFixed(2)},${(p.y*artwork.height/100).toFixed(2)} `;
    }
    previous = b.id;
  }
  if (d) paths.push({ osmId: way.id, kind: tags.highway, d: d.trim() });
}
await writeFile(new URL('src/data/map-calibration.js', root), `// Generated by node scripts/calibrate-map.mjs. Display coordinates only.\nexport const mapCalibration = ${JSON.stringify(calibration)};\n`);
await writeFile(new URL('src/data/map-roads.js', root), `// OSM contributors, ODbL 1.0. Generated by node scripts/calibrate-map.mjs.\nexport const mapRoads = ${JSON.stringify(paths)};\n`);
await writeFile(new URL('public/assets/map-registration.json', root), JSON.stringify({ ...calibration, controls, attribution: '© OpenStreetMap contributors', license: 'ODbL-1.0', sourceUrl: externalAssets.map.dataUrl, note: 'Visual registration of recorded OSM roads to hand-painted artwork; not surveyed navigation geometry.' }, null, 2));
console.log(`Calibrated ${controls.length - 4} image controls, ${triangles.length} unfolded triangles, ${paths.length} in-park road ways.`);
