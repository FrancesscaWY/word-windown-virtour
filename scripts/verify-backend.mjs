import { homedir } from 'node:os';
import { pathToFileURL } from 'node:url';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const { chromium } = await import(pathToFileURL(process.env.VIRTOUR_PLAYWRIGHT_PATH ?? `${homedir()}/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs`).href);
const origin = process.env.DEMO_URL ?? 'http://127.0.0.1:5173';
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH ?? '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox', '--enable-unsafe-swiftshader', '--use-angle=swiftshader'] });
await mkdir('artifacts/backend', { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${origin}/tour.html?mode=immersive`);
  await page.waitForSelector('#voice-input');
  const status = await page.request.get(`${origin}/api/status`);
  const config = await status.json();
  assert.equal(config.guide, 'connected');
  console.log('Connected:', config.mode, config.model);
  const question = '世界之窗有什么特色？请简短介绍并保留资料来源。';
  const firstResponse = page.waitForResponse(response => response.url().endsWith('/api/guide') && response.request().method() === 'POST', { timeout: 70000 });
  await page.locator('#voice-input').fill(question);
  await page.locator('#voice-form').evaluate(form => form.requestSubmit());
  const first = await (await firstResponse).json();
  assert.equal(first.status, 'success'); assert.match(first.text, /世界之窗/);
  assert.ok(first.traces.some(trace => trace.name === 'search_knowledge_base'));
  await page.waitForFunction(answer => document.querySelector('#conversation-log').textContent.includes(answer), first.text);
  const secondResponse = page.waitForResponse(response => response.url().endsWith('/api/guide'), { timeout: 70000 });
  await page.locator('#voice-input').fill('这些资料是实时的吗？用一句话回答。');
  await page.locator('#voice-form').evaluate(form => form.requestSubmit());
  const second = await (await secondResponse).json();
  assert.equal(second.status, 'success'); assert.match(second.text, /实时|快照|更新/);
  await page.waitForFunction(answer => document.querySelector('#conversation-log').textContent.includes(answer), second.text);
  await page.screenshot({ path: 'artifacts/backend/knowledge-mobile.png', fullPage: true });
  // A deliberately delayed response must never replace a newer local operation.
  let release, markStarted;
  const started = new Promise(resolve => { markStarted = resolve; });
  const delayed = new Promise(resolve => { release = resolve; });
  await page.route('**/api/guide', async route => {
    markStarted(); await delayed;
    await route.fulfill({ json: { status: 'success', text: 'STALE-ANSWER-MUST-NOT-APPEAR' } }).catch(() => {});
  });
  await page.locator('#voice-input').fill('介绍一下这里的交通安排');
  await page.locator('#voice-form').evaluate(form => form.requestSubmit());
  await started;
  await page.locator('#voice-input').fill('返回地图');
  await page.locator('#voice-form').evaluate(form => form.requestSubmit());
  await page.waitForFunction(() => document.querySelector('#guide-state-label').textContent !== '想一想…');
  release();
  await page.waitForTimeout(250);
  assert.doesNotMatch(await page.locator('#conversation-log').textContent(), /STALE-ANSWER/);
  await page.unroute('**/api/guide');
  await page.route('**/api/guide', route => route.fulfill({ status: 502, json: { error: 'GUIDE_UNAVAILABLE', message: '导游后端暂时无法完成回答，请稍后重试。' } }));
  await page.locator('#voice-input').fill('世界之窗有什么特色？');
  await page.locator('#voice-form').evaluate(form => form.requestSubmit());
  await page.waitForFunction(() => document.querySelector('#conversation-log').textContent.includes('暂时无法完成回答'));
  await page.locator('#voice-input').fill('找卫生间');
  await page.locator('#voice-form').evaluate(form => form.requestSubmit());
  await page.waitForFunction(() => document.querySelector('.map-viewport').dataset.facilityView === 'toilets');
  await page.screenshot({ path: 'artifacts/backend/fallback-mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
  await writeFile('artifacts/backend/verification.json', JSON.stringify({ config, question, first, second, cancellation: true, failureRecovery: true, pageErrors: errors }, null, 2));
  console.log('PASS: live knowledge answer, follow-up context, cancellation, failure recovery and local facilities.');
} finally { await browser.close(); }
